def reaction_title_en(vi_title: str, eq: str = "") -> str:
    """Chuyển tiêu đề phản ứng tiếng Việt sang tiếng Anh chuẩn hóa học (có cache)."""
    if vi_title in _RXN_CACHE:
        return _RXN_CACHE[vi_title]
    s = vi_title
    for src, dst in _RXN_REPLACEMENTS:
        s = re.sub(re.escape(src), dst, s, flags=re.IGNORECASE)
    # Chuẩn hóa chữ cái đầu và khoảng trắng
    s = re.sub(r"\s+", " ", s).strip()
    if s:
        s = s[0].upper() + s[1:]
    # Nếu vẫn còn dấu tiếng Việt chưa dịch hết (chủ đề ít gặp), tạo nhãn gọn từ chính phương trình cân bằng
    if re.search(r"[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]", s, re.IGNORECASE):
        clean_eq = re.sub(r"\[[^\]]*\]", "", eq).strip()
        parts = re.split(r"\s*(?:<=>|->)\s*", clean_eq, maxsplit=1)
        if len(parts) == 2:
            lhs = re.sub(r"\b\d+(?=[A-Z(])", "", parts[0]).strip()
            rhs = re.sub(r"\b\d+(?=[A-Z(])", "", parts[1]).replace("^", "").replace(" v", "").strip()
            s = f"Reaction: {lhs} → {rhs}"
    _RXN_CACHE[vi_title] = s
    return s
